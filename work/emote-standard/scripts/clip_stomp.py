"""Emote_Stomp - angry stomp (mad: a lost point / a bad shot).

Beats (30 fps): both fists clench, the right knee comes up high, weight on the left foot, shoulders up, head back (0-9)
-> STOMP: the right foot slams flat into the court at full speed, both arms thrust straight down and back, trunk crunches, head down (9-12)
-> impact bounce (12-16) -> smaller left stomp (16-24) -> hunched huff: shoulders up, fists rigid, head shakes "no", chest heaves (26-48)
-> exhale back to READY, the left hand back on the racket throat (48-62).  Golf: same body, empty fists."""
import numpy as np

import std
from ek import to_char

NAME = 'Emote_Stomp'
N = 66


def build(H):
    T = std.Tracks(H, N)
    ka = H.k
    S = lambda v: np.array(v) * ka
    wl0 = to_char(H.wrist_l0 - H.chest0)
    wr0 = to_char(H.wrist_r0 - H.chest0)
    pl0 = np.array(to_char(np.array(H.ctrl['arm_l'][1].location)))
    pr0 = np.array(to_char(np.array(H.ctrl['arm_r'][1].location)))
    kn0, pa0 = H.ready_hand_axes('l')
    sh0, fa0 = H.ready_racket_axes()
    Z = (0, 0, 0)
    T['hp'] = T.k3([(0, Z), (8, (-0.05, -0.01, 0.025)), (9, (-0.05, -0.01, 0.025)), (12, (-0.01, 0.01, -0.075)), (14, (0.0, 0.0, -0.09)), (17, (0.03, 0.0, -0.03)),
                    (21, (0.045, 0.0, 0.0)), (24, (0.01, 0.0, -0.06)), (27, (0.0, 0.0, -0.05)), (36, (0.0, 0.0, -0.035)), (48, (0, 0, -0.03)),
                    (58, (0, 0, 0.003)), (62, Z), (N - 1, Z)])
    T['hb'] = T.k3([(0, Z), (8, (-6, -4, 8)), (12, (10, 0, -4)), (17, (2, 3, -6)), (21, (-2, 5, -8)), (24, (8, 0, 2)), (30, (5, 0, 0)), (48, (4, 0, 0)), (60, Z), (N - 1, Z)])
    T.torso([(0, Z), (8, (-8, 0, 10)), (12, (20, 0, -6)), (14, (22, 0, -6)), (17, (6, 0, -4)), (21, (-3, 0, -6)), (24, (16, 0, 4)), (28, (12, 0, 0)),
             (34, (8, 0, 0)), (38, (13, 0, 0)), (42, (8, 0, 0)), (48, (10, 0, 0)), (60, (0, 0, 0)), (N - 1, Z)])
    T.neckhead([(0, Z), (8, (-12, 0, -6)), (12, (16, 0, 4)), (14, (18, 0, 4)), (17, (4, 0, 0)), (21, (-6, 0, 0)), (24, (14, 0, 0)), (29, (6, 0, 0)),
                (32, (6, 0, 15)), (36, (8, 0, -15)), (40, (6, 0, 13)), (44, (8, 0, -7)), (48, (6, 0, 0)), (60, Z), (N - 1, Z)])
    for s, lag in (('r', 0), ('l', 1)):
        T['cl_' + s] = T.k3([(0, Z), (8, (12, -4, 0)), (12, (14, 2, 0)), (17, (8, 0, 0)), (24, (12, 2, 0)), (30, (12, 0, 0)), (38, (9, 0, 0)), (44, (11, 0, 0)),
                              (50, (2, 0, 0)), (60, Z), (N - 1, Z)], lag=lag)[:, :2]
    # fists: up at the chest on the wind-up, thrust straight down/back on the stomp
    T['wl'] = T.k3([(0, wl0), (3, wl0 + [-0.06, -0.05, -0.01]), (8, S([-0.22, 0.20, -0.14])), (9, S([-0.22, 0.20, -0.13])), (12, S([-0.25, -0.07, -0.47])),
                    (14, S([-0.25, -0.08, -0.46])), (18, S([-0.24, 0.10, -0.32])), (21, S([-0.23, 0.15, -0.24])), (24, S([-0.25, -0.06, -0.46])),
                    (30, S([-0.24, -0.04, -0.45])), (46, S([-0.24, -0.03, -0.45])), (54, S([-0.12, 0.20, -0.36])), (59, wl0), (N - 1, wl0)])
    T['wr'] = T.k3([(0, wr0), (3, wr0), (8, S([0.22, 0.20, -0.14])), (9, S([0.22, 0.20, -0.13])), (12, S([0.25, -0.07, -0.46])), (14, S([0.25, -0.08, -0.45])),
                    (18, S([0.24, 0.10, -0.32])), (21, S([0.23, 0.15, -0.24])), (24, S([0.25, -0.06, -0.45])), (30, S([0.24, -0.04, -0.44])),
                    (46, S([0.24, -0.03, -0.44])), (54, S([0.14, 0.10, -0.40])), (59, wr0), (N - 1, wr0)])
    T['pl'] = T.k3([(0, pl0), (8, S([-0.75, -0.2, -0.3])), (12, S([-0.5, -0.4, 0.1])), (46, S([-0.5, -0.4, 0.1])), (58, pl0), (N - 1, pl0)])
    T['pr'] = T.k3([(0, pr0), (8, S([0.75, -0.2, -0.3])), (12, S([0.5, -0.4, 0.1])), (46, S([0.5, -0.4, 0.1])), (58, pr0), (N - 1, pr0)])
    T['kn_l'] = T.k3([(0, kn0), (3, kn0), (8, (0.3, 0.6, 0.75)), (12, (0.05, -0.25, -0.97)), (46, (0.05, -0.2, -0.97)), (54, (0.3, 0.6, -0.4)), (59, kn0), (N - 1, kn0)])
    T['pa_l'] = T.k3([(0, pa0), (3, pa0), (8, (0.5, -0.85, 0.0)), (12, (1.0, 0.0, 0.0)), (46, (1.0, 0.0, 0.0)), (59, pa0), (N - 1, pa0)])
    T['shaft'] = T.k3([(0, sh0), (3, sh0), (8, (0.65, 0.15, 0.74)), (12, (0.25, -0.55, -0.80)), (46, (0.25, -0.5, -0.83)), (54, (0.2, 0.6, -0.6)), (59, sh0), (N - 1, sh0)])
    T['face'] = T.k3([(0, fa0), (3, fa0), (8, (-0.9, 0.2, 0.2)), (12, (-0.95, 0.0, 0.3)), (46, (-0.95, 0.0, 0.3)), (59, fa0), (N - 1, fa0)])
    T['curl_l'] = T.k1([(0, 0), (2, 0), (5, 1), (50, 1), (57, 0), (N - 1, 0)])
    T['curl_r_golf'] = T.k1([(0, 0), (2, 0), (5, 1), (50, 1), (57, 0), (N - 1, 0)])
    # feet: right knee up and STOMP (accelerating into the court), then a smaller left one
    T['ank_r'] = T.k3([(0, Z), (3, Z), (8, (-0.03, 0.10, 0.30)), (9, (-0.03, 0.10, 0.31)), (12, Z), (N - 1, Z)])
    T['heel_r'] = T.k1([(0, 0), (3, 0), (8, -6), (9, -6), (12, 0), (N - 1, 0)])
    T.impact('ank_r', 9, 12)
    T.impact('heel_r', 9, 12)
    T['kp_r'] = T.k3([(0, Z), (8, (0, 0.2, 0.35)), (12, Z), (N - 1, Z)])
    T['ank_l'] = T.k3([(0, Z), (16, Z), (21, (0.02, 0.06, 0.16)), (22, (0.02, 0.06, 0.165)), (24, Z), (N - 1, Z)])
    T['heel_l'] = T.k1([(0, 0), (16, 0), (21, -4), (24, 0), (N - 1, 0)])
    T.impact('ank_l', 22, 24)
    T['kp_l'] = T.k3([(0, Z), (21, (0, 0.2, 0.25)), (24, Z), (N - 1, Z)])
    return N, std.pose_fn(H, T, golf=getattr(H, 'prop', 'racket') == 'none')
