"""Emote_FistPump - "Yes! / Come on!" (excited, short: a won point).

Beats (30 fps): the free (left) hand lets go of the racket throat and cocks a fist up by the shoulder, chest opens (0-7)
-> PUMP: the elbow drives down to the ribs, fist to the hip, the left knee kicks up, trunk crunches, head nods (7-11)
-> rebound (11-14) -> second, shorter pump with the foot down (14-17) -> held "COME ON!" crouch with a shaking fist (17-27)
-> back to READY, the left hand returns to the throat (27-44).  The racket arm drops low and out for balance.
Golf (empty hands): same body, the right hand a loose fist."""
import numpy as np

import ek
import std
from ek import to_char

NAME = 'Emote_FistPump'
N = 48


def build(H):
    T = std.Tracks(H, N)
    ka = H.k
    S = lambda v: np.array(v) * ka
    wl0 = to_char(H.wrist_l0 - H.chest0)
    wr0 = to_char(H.wrist_r0 - H.chest0)
    pl0 = np.array(to_char(np.array(H.ctrl['arm_l'][1].location)))
    pr0 = np.array(to_char(np.array(H.ctrl['arm_r'][1].location)))
    kn0, pa0 = H.ready_hand_axes('l')
    sh0, fa0 = H.ready_racket_axes()

    T['hp'] = T.k3([(0, (0, 0, 0)), (6, (0.0, 0.0, 0.02)), (10, (0.035, -0.01, -0.05)), (13, (0.02, 0.0, -0.012)), (16, (0.01, -0.01, -0.045)),
                    (19, (0.01, -0.01, -0.04)), (27, (0.0, 0.0, -0.032)), (40, (0, 0, 0.004)), (44, (0, 0, 0)), (N - 1, (0, 0, 0))])
    T['hb'] = T.k3([(0, (0, 0, 0)), (6, (-4, 0, -4)), (10, (10, 3, 6)), (13, (2, 1, 2)), (16, (9, 0, 5)), (27, (6, 0, 3)), (42, (0, 0, 0)), (N - 1, (0, 0, 0))])
    T.torso([(0, (0, 0, 0)), (6, (-7, 0, -8)), (10, (14, -4, 12)), (13, (1, 0, 3)), (16, (11, -3, 9)), (19, (8, 0, 6)), (27, (6, 0, 4)),
             (40, (-1, 0, 0)), (45, (0, 0, 0)), (N - 1, (0, 0, 0))])
    T.neckhead([(0, (0, 0, 0)), (6, (-10, 0, 0)), (10, (14, 4, -6)), (13, (-2, 0, -2)), (16, (10, 3, -4)), (19, (-6, 0, 0)),
                (21, (-8, 3, 0)), (23, (-6, -3, 0)), (25, (-8, 2, 0)), (27, (-5, 0, 0)), (40, (1, 0, 0)), (45, (0, 0, 0)), (N - 1, (0, 0, 0))])
    T['cl_l'] = T.k3([(0, (0, 0, 0)), (6, (10, -4, 0)), (10, (-6, 8, 0)), (13, (3, 0, 0)), (16, (-5, 6, 0)), (27, (-2, 4, 0)), (42, (0, 0, 0)), (N - 1, (0, 0, 0))], lag=1)[:, :2]
    T['cl_r'] = T.k3([(0, (0, 0, 0)), (10, (-3, 4, 0)), (27, (-2, 2, 0)), (42, (0, 0, 0)), (N - 1, (0, 0, 0))])[:, :2]
    # the pumping (left) fist
    T['wl'] = T.k3([(0, wl0), (2, wl0 + [-0.05, -0.04, -0.01]), (7, S([-0.31, 0.10, 0.10])), (8, S([-0.31, 0.11, 0.11])), (11, S([-0.26, 0.20, -0.30])),
                    (14, S([-0.30, 0.15, -0.04])), (17, S([-0.26, 0.20, -0.32])), (19, S([-0.26, 0.20, -0.29])), (21, S([-0.27, 0.20, -0.33])),
                    (23, S([-0.26, 0.20, -0.29])), (25, S([-0.27, 0.20, -0.32])), (27, S([-0.26, 0.20, -0.30])), (34, S([-0.12, 0.25, -0.31])),
                    (40, wl0 + [-0.01, -0.005, 0.005]), (43, wl0), (N - 1, wl0)])
    T['pl'] = T.k3([(0, pl0), (7, S([-0.70, -0.20, -0.45])), (11, S([-0.75, -0.45, -0.45])), (17, S([-0.75, -0.45, -0.45])), (30, S([-0.6, -0.45, -0.5])),
                    (42, pl0), (N - 1, pl0)])
    T['kn_l'] = T.k3([(0, kn0), (2, kn0), (7, (-0.10, 0.20, 0.97)), (11, (0.05, 0.35, 0.93)), (17, (0.05, 0.35, 0.93)), (30, (0.15, 0.5, 0.85)),
                      (42, kn0), (N - 1, kn0)])
    T['pa_l'] = T.k3([(0, pa0), (2, pa0), (7, (0.6, -0.8, 0.0)), (11, (0.7, -0.7, 0.0)), (30, (0.8, -0.5, 0.1)), (42, pa0), (N - 1, pa0)])
    T['curl_l'] = T.k1([(0, 0), (2, 0), (6, 1), (36, 1), (42, 0), (N - 1, 0)])
    # the racket arm drops low and out for balance
    T['wr'] = T.k3([(0, wr0), (4, wr0), (10, S([0.28, 0.10, -0.40])), (17, S([0.28, 0.10, -0.41])), (27, S([0.27, 0.11, -0.40])), (40, wr0), (N - 1, wr0)])
    T['pr'] = T.k3([(0, pr0), (10, S([0.6, -0.4, -0.2])), (27, S([0.6, -0.4, -0.2])), (40, pr0), (N - 1, pr0)])
    T['shaft'] = T.k3([(0, sh0), (4, sh0), (10, (0.55, 0.45, -0.70)), (12, (0.55, 0.50, -0.67)), (17, (0.55, 0.45, -0.70)), (27, (0.55, 0.45, -0.70)),
                       (40, sh0), (N - 1, sh0)])
    T['face'] = T.k3([(0, fa0), (4, fa0), (10, (-0.7, 0.5, 0.4)), (27, (-0.7, 0.5, 0.4)), (40, fa0), (N - 1, fa0)])
    T['curl_r_golf'] = T.k1([(0, 0), (4, 0), (9, 0.75), (36, 0.75), (42, 0), (N - 1, 0)])
    # left knee kicks up on the first pump (weight on the right foot)
    T['ank_l'] = T.k3([(0, (0, 0, 0)), (7, (0, 0, 0)), (10, (0.03, 0.11, 0.18)), (12, (0.03, 0.12, 0.17)), (15, (0, 0.03, 0.0)), (N - 1, (0, 0, 0))])
    T['heel_l'] = T.k1([(0, 0), (7, 0), (10, 30), (12, 26), (15, 0), (N - 1, 0)])
    T['heel_r'] = T.k1([(0, 0), (5, 0), (7, 8), (10, 0), (N - 1, 0)])
    T['kp_l'] = T.k3([(0, (0, 0, 0)), (10, (0, 0.1, 0.2)), (15, (0, 0, 0)), (N - 1, (0, 0, 0))])
    return N, std.pose_fn(H, T, golf=getattr(H, 'prop', 'racket') == 'none')
